#pragma once

#include "Order.hpp"
#include "OrderBook.hpp"
#include "Trade.hpp"

#include <cstdint>
#include <vector>

/**
 * @brief Result returned after submitting an order to the ExecutionEngine.
 */
struct ExecutionResult {
    Order order;                 ///< Updated order state after matching
    std::vector<Trade> trades;   ///< List of trades generated by this order
};

/**
 * @brief Simulated matching engine that processes orders and maintains an order book.
 */
class ExecutionEngine {
public:
    ExecutionEngine() = default;

    /**
     * @brief Submits an incoming order to the engine for matching.
     *
     * Validates the order, executes matching trades against the order book,
     * updates filled and remaining quantities, cancels any unfilled market order remainder,
     * and rests any unfilled limit order in the order book.
     *
     * @param order The incoming order.
     * @return ExecutionResult Updated order and any generated trade records.
     */
    ExecutionResult submit_order(Order order);

    /**
     * @brief Access the internal order book.
     */
    const OrderBook& get_order_book() const { return book_; }
    OrderBook& get_order_book() { return book_; }

    /**
     * @brief Retrieves all historical trades executed by the engine.
     */
    const std::vector<Trade>& get_trade_history() const { return trades_; }

    /**
     * @brief Resets the engine, clearing book and trade records.
     */
    void reset();

private:
    OrderBook book_;
    std::vector<Trade> trades_;
    TradeId next_trade_id_{1};

    void match_buy(ExecutionResult& result);
    void match_sell(ExecutionResult& result);
};
